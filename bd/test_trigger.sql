-- [Шаг 1] Поиск тестового владельца (owner_id) и собаки (dog_id)
SELECT u.id as owner_id, u.first_name, u.last_name, d.id as dog_id, d.name as dog_name
FROM users u 
JOIN dogs d ON u.id = d.owner_id 
LIMIT 1;

-- Подставьте полученные значения ниже:
-- Например: owner_id = 2, dog_id = 3


-- [Шаг 2] Создание заказа с использованием хранимой функции create_order()
-- Эта функция запишет заказ в `orders` и свяжет собаку в `order_dogs`
SELECT create_order(
    2, -- owner_id (замените на ваш)
    NOW(), -- planned_start_at
    NOW() + interval '1 hour', -- planned_end_at
    'Тестовая ул., д. 1', -- walk_address
    1500, -- total_cost
    ARRAY[3]::INTEGER[] -- dog_ids (массив dog_id, замените на ваш)
);

-- Запомните полученный ID заказа (например, 10005). Подставьте его в шагах ниже.


-- [Шаг 3] Выбор свободного выгульщика (walker_id)
SELECT u.id as walker_id, u.first_name, u.last_name
FROM users u 
JOIN user_roles ur ON u.id = ur.user_id 
WHERE ur.role_id = 2 
LIMIT 1;

-- Подставьте полученное значение ниже:
-- Например: walker_id = 4


-- [Шаг 4] Принятие заказа с использованием функции accept_order()
-- Эта функция проверит статус заказа, назначит выгульщика и сменит статус на 'принят' (2)
SELECT accept_order(10005, 4); -- (заказ_id, выгульщик_id)


-- [Шаг 5] Проверка: Прогулка еще не начата, отчета нет
-- Проверим таблицу walks (должна быть пустой для этого заказа)
SELECT * FROM walks WHERE order_id = 10005;

-- Проверим таблицу reports (отчета быть не должно)
SELECT r.* 
FROM reports r 
JOIN walks w ON r.walk_id = w.id 
WHERE w.order_id = 10005;


-- [Шаг 6] Завершение прогулки функцией complete_walk()
-- Эта функция переводит статус заказа в 'завершен' (3) и вносит запись в walks со статусом 'завершена'
SELECT complete_walk(10005, NOW(), NOW() + interval '30 minutes');

-- Запомните полученный ID прогулки (например, 5002)


-- [Шаг 7] Проверка: Срабатывание триггера trg_generate_report
-- При смене статуса прогулки на 'завершена' триггер trg_generate_report 
-- должен был автоматически создать запись в таблице reports.
SELECT * FROM reports WHERE walk_id = 5002;

